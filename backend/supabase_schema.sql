-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  leetcode_id TEXT UNIQUE NOT NULL,
  avatar_url TEXT DEFAULT '',
  total_easy INT DEFAULT 0,
  total_medium INT DEFAULT 0,
  total_hard INT DEFAULT 0,
  total_score INT DEFAULT 0,
  tier TEXT DEFAULT 'Novice Coder',
  xp INT DEFAULT 0,
  push_token TEXT DEFAULT '',
  last_synced_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. EVENTS / TOURNAMENTS TABLE
CREATE TABLE IF NOT EXISTS public.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT DEFAULT '',
  creator_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  start_date TIMESTAMPTZ NOT NULL,
  end_date TIMESTAMPTZ NOT NULL,
  duration_days INT NOT NULL,
  invite_code TEXT UNIQUE NOT NULL,
  mode TEXT DEFAULT 'standard',
  topic TEXT DEFAULT '',
  status TEXT DEFAULT 'upcoming' CHECK(status IN ('upcoming', 'active', 'completed')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. EVENT PARTICIPANTS TABLE
CREATE TABLE IF NOT EXISTS public.event_participants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  easy_at_join INT DEFAULT 0,
  medium_at_join INT DEFAULT 0,
  hard_at_join INT DEFAULT 0,
  current_easy INT DEFAULT 0,
  current_medium INT DEFAULT 0,
  current_hard INT DEFAULT 0,
  score INT DEFAULT 0,
  joined_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_event_participant UNIQUE (event_id, user_id)
);

-- 4. DAILY PROGRESS TRACKING TABLE
CREATE TABLE IF NOT EXISTS public.daily_progress (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id BIGINT NOT NULL REFERENCES public.event_participants(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  easy_solved INT DEFAULT 0,
  medium_solved INT DEFAULT 0,
  hard_solved INT DEFAULT 0,
  daily_score INT DEFAULT 0,
  CONSTRAINT unique_participant_date UNIQUE (participant_id, date)
);

-- 5. LIVE NOTIFICATIONS & ALERTS TABLE
CREATE TABLE IF NOT EXISTS public.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  message TEXT NOT NULL,
  type TEXT DEFAULT 'solve_alert',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 🚀 INDEXES FOR HIGH-PERFORMANCE QUERIES
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);
CREATE INDEX IF NOT EXISTS idx_users_leetcode_id ON public.users(leetcode_id);
CREATE INDEX IF NOT EXISTS idx_users_total_score ON public.users(total_score DESC);
CREATE INDEX IF NOT EXISTS idx_events_invite_code ON public.events(invite_code);
CREATE INDEX IF NOT EXISTS idx_events_status ON public.events(status);
CREATE INDEX IF NOT EXISTS idx_events_creator ON public.events(creator_id);
CREATE INDEX IF NOT EXISTS idx_event_participants_event ON public.event_participants(event_id);
CREATE INDEX IF NOT EXISTS idx_event_participants_user ON public.event_participants(user_id);
CREATE INDEX IF NOT EXISTS idx_daily_progress_participant ON public.daily_progress(participant_id);
CREATE INDEX IF NOT EXISTS idx_notifications_event ON public.notifications(event_id);
CREATE INDEX IF NOT EXISTS idx_notifications_created ON public.notifications(created_at DESC);

